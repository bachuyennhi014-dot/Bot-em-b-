export function decorateTitle(title, pairIndex = 0) {
  const pair = TITLE_DECOR_PAIRS[pairIndex % TITLE_DECOR_PAIRS.length];
  // Calculate text length without Discord emoji tags like <:name:id> or <a:name:id>
  const cleanTitle = String(title || '').replace(/<a?:\w+:\d+>/g, '').trim();

  // If title is very long (> 42 chars), use only 1 emoji at the beginning
  if (cleanTitle.length > 42) {
    return `${pair[0]} ${title}`;
  }
  // If title is long (> 22 chars), use 2 emojis distributed 1 on each side
  if (cleanTitle.length > 22) {
    return `${pair[0]} ${title} ${pair[3]}`;
  }
  // For short titles (<= 22 chars), use emojis distributed on both sides
  return `${pair[0]} ${pair[1]} ${title} ${pair[2]} ${pair[3]}`;
}

